
#!/usr/bin/env python3
"""Reproducible Phase 4 experiment and analysis pipeline."""

import argparse
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results_phase4"

EXPERIMENTS = [
    "eta_multiseed",
    "phase4_network_sizes",
    "phase4_window_width",
    "phase4_uav_delay",
    "phase4_ch_failure",
    "phase4_clock_drift",
]

# Config name -> output directory name
OUTPUT_DIRS = {
    "eta_multiseed": "eta_multiseed",
    "phase4_network_sizes": "network_sizes",
    "phase4_window_width": "window_width",
    "phase4_uav_delay": "phase4_uav_delay",
    "phase4_ch_failure": "phase4_ch_failure",
    "phase4_clock_drift": "phase4_clock_drift",
}

# Required existing inputs that are not regenerated by Phase 4.
BASELINE_CSV = RESULTS / "phase3_eval" / "runs.csv"

PPO_MONITORS = [
    ROOT / "models/phase3_ppo/A1_ppo-scoring_ws_train.monitor.csv",
    ROOT / "models/phase3_ppo/A2_ppo-scoring_ws_train.monitor.csv",
    ROOT / "models/phase3_ppo/A3_ppo-scoring_ws_train.monitor.csv",
    ROOT / "models/phase3_ppo/A4_ppo-scoring_ws_train.monitor.csv",
    ROOT / "models/phase3_fixes/A_ppo-scoring_ws_train.monitor.csv",
    ROOT / "models/phase3_fixes/B_ppo-scoring_ws_train.monitor.csv",
    ROOT / "models/phase3_fixes/C_ppo-scoring_ws_train.monitor.csv",
    ROOT / "models/phase3_fixes/D_ppo-scoring_ws_train.monitor.csv",
]


def execute(command):
    """Run a command from the repository root."""
    printable = " ".join(str(x) for x in command)
    print(f"\n>>> {printable}", flush=True)

    subprocess.run(
        [str(x) for x in command],
        cwd=ROOT,
        check=True,
    )


def check_inputs():
    """Fail early if required data or scripts are missing."""
    missing = []

    required_files = [
        BASELINE_CSV,
        *PPO_MONITORS,
        ROOT / "analysis/aggregate.py",
        ROOT / "analysis/paired_eta.py",
        ROOT / "analysis/paired_window_width.py",
        ROOT / "analysis/paired_parameter_sweeps.py",
        ROOT / "analysis/plot_eta.py",
        ROOT / "analysis/plot_network_sizes.py",
        ROOT / "analysis/plot_window_width.py",
        ROOT / "analysis/plot_lifetime.py",
        ROOT / "analysis/plot_parameter_sweeps.py",
        ROOT / "analysis/plot_ppo_learning_curves.py",
    ]

    for path in required_files:
        if not path.is_file():
            missing.append(path.relative_to(ROOT))

    if missing:
        details = "\n".join(f"  - {p}" for p in missing)
        raise FileNotFoundError(
            "Required inputs are missing:\n" + details
        )

    print("All required baseline, model-log and analysis files exist.")


def run_experiments(jobs, overwrite):
    """Execute all six Phase 4 simulation configurations."""
    existing = []

    for config_name, output_name in OUTPUT_DIRS.items():
        runs_file = RESULTS / output_name / "runs.csv"
        if runs_file.exists():
            existing.append(runs_file.relative_to(ROOT))

    if existing and not overwrite:
        details = "\n".join(f"  - {p}" for p in existing)
        raise FileExistsError(
            "Existing experiment results detected:\n"
            f"{details}\n\n"
            "No experiments were started. Use --overwrite only if "
            "you intentionally want to rerun all six experiments."
        )

    for config_name in EXPERIMENTS:
        config = ROOT / "configs" / f"{config_name}.toml"

        if not config.is_file():
            raise FileNotFoundError(f"Missing configuration: {config}")

        execute([
            sys.executable,
            "-m",
            "experiments.run_experiment",
            config,
            "-j",
            jobs,
            "--results",
            RESULTS,
        ])


def aggregate_all():
    """Generate summary.csv and summary.md for every experiment."""
    for output_name in OUTPUT_DIRS.values():
        runs = RESULTS / output_name / "runs.csv"

        execute([
            sys.executable,
            "analysis/aggregate.py",
            runs,
        ])


def run_analysis():
    """Regenerate all Phase 4 statistics and figures."""
    print("\n========== AGGREGATION ==========")
    aggregate_all()

    print("\n========== ETA QUANTILE ANALYSIS ==========")
    eta_runs = RESULTS / "eta_multiseed" / "runs.csv"

    execute([
        sys.executable,
        "analysis/paired_eta.py",
        eta_runs,
    ])

    execute([
        sys.executable,
        "analysis/plot_eta.py",
        eta_runs,
    ])

    print("\n========== NETWORK SIZE ANALYSIS ==========")
    execute([
        sys.executable,
        "analysis/plot_network_sizes.py",
    ])

    print("\n========== WAKE WINDOW ANALYSIS ==========")
    execute([
        sys.executable,
        "analysis/paired_window_width.py",
    ])

    execute([
        sys.executable,
        "analysis/plot_window_width.py",
    ])

    print("\n========== LIFETIME ANALYSIS ==========")
    execute([
        sys.executable,
        "analysis/plot_lifetime.py",
    ])

    print("\n========== PARAMETER SWEEP STATISTICS ==========")
    execute([
        sys.executable,
        "analysis/paired_parameter_sweeps.py",
    ])

    print("\n========== PARAMETER SWEEP FIGURES ==========")
    execute([
        sys.executable,
        "analysis/plot_parameter_sweeps.py",
    ])

    print("\n========== PPO TRAINING FIGURES ==========")
    execute([
        sys.executable,
        "analysis/plot_ppo_learning_curves.py",
    ])

    print("\n========== PHASE 4 PIPELINE COMPLETE ==========")
    print(f"Results directory: {RESULTS}")


def main():
    parser = argparse.ArgumentParser(
        description="Run and analyze the Phase 4 WSN-UAV experiments."
    )

    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--run",
        action="store_true",
        help="Run all six experiments and regenerate all analyses.",
    )
    mode.add_argument(
        "--analysis-only",
        action="store_true",
        help="Regenerate analyses from existing experiment CSVs.",
    )

    parser.add_argument(
        "-j",
        "--jobs",
        type=int,
        default=4,
        help="Parallel experiment jobs (default: 4).",
    )

    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow --run to rerun experiments with existing runs.csv files.",
    )

    args = parser.parse_args()

    if args.jobs < 1:
        parser.error("--jobs must be at least 1")

    if args.overwrite and not args.run:
        parser.error("--overwrite can only be used with --run")

    check_inputs()

    if args.run:
        print("\n========== RUNNING PHASE 4 EXPERIMENTS ==========")
        run_experiments(args.jobs, args.overwrite)

    # Check all experiment outputs before starting analysis.
    missing_runs = [
        RESULTS / output_name / "runs.csv"
        for output_name in OUTPUT_DIRS.values()
        if not (RESULTS / output_name / "runs.csv").is_file()
    ]

    if missing_runs:
        details = "\n".join(f"  - {p.relative_to(ROOT)}" for p in missing_runs)
        raise FileNotFoundError(
            "Cannot run complete analysis. Missing experiment CSVs:\n"
            + details
        )

    run_analysis()


if __name__ == "__main__":
    main()

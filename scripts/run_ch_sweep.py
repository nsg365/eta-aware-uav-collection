#!/usr/bin/env python3
"""Run CH-count sweep experiments for specified target cluster counts.

Reads configs/ch_sweep_params.json (produced by calibrate_ch_count.py) to look up
the (hotspot_count, max_cluster_size) for each target, generates a TOML config on
the fly, and invokes experiments.run_experiment for it.

Usage (after calibrate_ch_count.py):
  python3 scripts/run_ch_sweep.py --targets 5 10 -j 4    # person 1
  python3 scripts/run_ch_sweep.py --targets 15 20 -j 4   # person 2
  python3 scripts/run_ch_sweep.py --targets 5 10 15 20   # all at once

The results land in:
  results/ch_sweep_target_05/   results/ch_sweep_target_10/  ...

Each directory contains a standard runs.csv with one row per (seed × variant).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

DEFAULT_PARAMS_FILE = REPO / "configs" / "ch_sweep_params.json"
DEFAULT_RESULTS_DIR = REPO / "results"

# Routing variants to run (all four classical methods)
VARIANTS = [
    ("tour",              "tour"),
    ("nearest_feasible",  "nearest-feasible"),
    ("data_greedy",       "data-greedy"),
    ("energy_data_score", "energy-data-score"),
]

# Simulation params – same intent as phase2_gaussian_speed_jitter_p010.toml.
# NOTE: ns-3 uses --uavSpeedStd (m/s absolute), not --uavSpeedJitter (fraction).
# jitter=0.1 at 10 m/s  →  std = 1.0 m/s  (equivalent ±10% at mean speed)
SIM_PARAMS = dict(
    simTime=7200.0,
    uavSpeed=10.0,
    uavSpeedStd=1.0,    # was uavSpeedJitter=0.1 in the TOML (not a valid ns-3 arg)
    wakeMode="scheduled",
    etaMinSamples=5,
    adaptiveLateMargin=20.0,
    uavDelayProb=0.0,
    uavDelayMin=1.0,
    uavDelayMax=5.0,
    # etaQuantile is per-variant, not in base sim params
)

SEEDS = list(range(1, 11))  # seeds 1–10


# ---------------------------------------------------------------------------
# TOML generation
# ---------------------------------------------------------------------------

def _toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return f'"{v}"'
    return str(v)


def generate_toml(target: int, hc: int, mcs: int | None) -> str:
    """Build a TOML config string for one target cluster count."""
    exp_name = f"ch_sweep_target_{target:02d}"
    topo_lines = [
        'area_m = 500.0',
        'sensor_range_m = 80.0',
        'dbscan_kappa = 0.8',
        'dbscan_min_samples = 3',
        'uav_range_m = 30.0',
        'alpha = 0.5',
        'min_candidates = 2',
        'depot_x = 0.0',
        'depot_y = 0.0',
        'deployment_mode = "gaussian_hotspot"',
        f'hotspot_count = {hc}',
        'hotspot_std_m = 25.0',
    ]
    if mcs is not None:
        topo_lines.append(f'max_cluster_size = {mcs}')

    sim_lines = [f"{k} = {_toml_value(v)}" for k, v in SIM_PARAMS.items()
                 if k != "etaQuantile"]  # etaQuantile goes in each variant

    variant_blocks = "\n".join(
        textwrap.dedent(f"""\
        [[variant]]
        name = "{name}"
        routing = "{routing}"
        etaQuantile = 0.95
        """)
        for name, routing in VARIANTS
    )

    seeds_str = ", ".join(str(s) for s in SEEDS)
    toml = textwrap.dedent(f"""\
    # Auto-generated by run_ch_sweep.py
    # Target cluster count: ~{target}
    # Topology params: hotspot_count={hc}, max_cluster_size={mcs}

    [experiment]
    name = "{exp_name}"
    num_sensors = [1000]
    seeds = [{seeds_str}]

    [topology]
    {chr(10).join(topo_lines)}

    [simulation]
    {chr(10).join(sim_lines)}

    {variant_blocks}""")
    return toml


# ---------------------------------------------------------------------------
# Experiment runner
# ---------------------------------------------------------------------------

def run_target(target: int, params: dict, jobs: int, results_dir: Path) -> int:
    """Generate TOML for `target`, write it to a temp file, run experiment. Returns exit code."""
    hc = params["hotspot_count"]
    mcs = params["max_cluster_size"]
    median = params["median_clusters"]
    std = params["std_clusters"]

    print()
    print("=" * 70)
    print(f"TARGET: ~{target} clusters  "
          f"(hotspot_count={hc}, max_cluster_size={mcs}, "
          f"median={median:.1f}±{std:.2f})")
    print("=" * 70)

    toml_content = generate_toml(target, hc, mcs)

    # Write to a named temp file so run_experiment.py can read it
    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".toml", prefix=f"ch_sweep_{target:02d}_",
        dir=REPO / "configs", delete=False
    ) as tf:
        tf.write(toml_content)
        toml_path = Path(tf.name)

    print(f"Config written to: {toml_path.name}")
    print(f"Running {len(SEEDS)} seeds × {len(VARIANTS)} variants "
          f"= {len(SEEDS) * len(VARIANTS)} simulations, {jobs} parallel\n")

    cmd = [
        sys.executable, "-m", "experiments.run_experiment",
        str(toml_path),
        "-j", str(jobs),
        "--results", str(results_dir),
    ]

    try:
        result = subprocess.run(cmd, cwd=REPO)
        return result.returncode
    finally:
        # Clean up the temp config (results are already written)
        toml_path.unlink(missing_ok=True)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--targets", type=int, nargs="+", required=True,
        metavar="N",
        help=(
            "Target cluster counts to run, e.g. --targets 5 10  or  --targets 15 20. "
            "Must match keys in ch_sweep_params.json."
        ),
    )
    ap.add_argument(
        "-j", "--jobs", type=int, default=4,
        help="Parallel simulation jobs (default: 4)",
    )
    ap.add_argument(
        "--params-file", type=Path, default=DEFAULT_PARAMS_FILE,
        help=f"Path to calibration JSON (default: {DEFAULT_PARAMS_FILE})",
    )
    ap.add_argument(
        "--results", type=Path, default=DEFAULT_RESULTS_DIR,
        help=f"Root results directory (default: {DEFAULT_RESULTS_DIR})",
    )
    a = ap.parse_args()

    # Load calibration lookup table
    if not a.params_file.exists():
        sys.exit(
            f"ERROR: {a.params_file} not found.\n"
            f"Run calibration first:\n"
            f"  python3 scripts/calibrate_ch_count.py"
        )

    with open(a.params_file) as f:
        calib = json.load(f)

    targets_map: dict[str, dict] = calib["targets"]

    # Validate requested targets
    missing = [t for t in a.targets if str(t) not in targets_map]
    if missing:
        available = sorted(int(k) for k in targets_map)
        sys.exit(
            f"ERROR: Targets {missing} not found in {a.params_file}.\n"
            f"Available targets: {available}\n"
            f"Re-run calibrate_ch_count.py with --targets {' '.join(str(t) for t in a.targets)}"
        )

    print(f"CH-count sweep: targets = {a.targets}, {a.jobs} parallel jobs")
    print(f"Calibration file: {a.params_file}")
    print(f"Results root: {a.results}")

    failed: list[int] = []
    for target in sorted(a.targets):
        rc = run_target(target, targets_map[str(target)], a.jobs, a.results)
        if rc != 0:
            print(f"ERROR: experiment for target={target} exited with code {rc}", file=sys.stderr)
            failed.append(target)

    print()
    if failed:
        print(f"DONE with errors for targets: {failed}")
        sys.exit(1)
    else:
        print(f"ALL DONE. Results in:")
        for t in sorted(a.targets):
            exp_name = f"ch_sweep_target_{t:02d}"
            print(f"  {a.results / exp_name / 'runs.csv'}")
        print()
        print("Next: python3 scripts/plot_ch_sweep.py")


if __name__ == "__main__":
    main()

// Shared simulation state: topology, per-sensor energy ledger, CH buffers and metrics.
// The 802.15.4 member->CH hop is NOT simulated with the ns-3 lr-wpan model: it is an analytic
// energy/loss abstraction (docs/DESIGN_DECISIONS.md D1). The CH<->UAV Wi-Fi link is simulated.
#ifndef WSN_UAV_WORLD_H
#define WSN_UAV_WORLD_H

#include "config.h"

#include "ns3/core-module.h"
#include "ns3/energy-module.h"
#include "ns3/wifi-module.h"

#include <string>
#include <vector>

namespace wsnuav
{

enum class Role
{
    MEMBER,
    PRIMARY,
    BACKUP
};

struct Sensor
{
    uint32_t id;
    double x, y;
    uint32_t cluster;
    Role role;

    // Energy ledger [J]. Wi-Fi energy comes from ns-3 (wifiEnergy) for CH-capable nodes.
    double e154Tx = 0, e154Rx = 0;
    ns3::Ptr<ns3::energy::DeviceEnergyModel> wifiEnergy; // null for plain members

    bool alive = true;
    double deathTime = -1;
    uint64_t generated = 0;
};

struct Cluster
{
    uint32_t id;
    double meetX, meetY;
    uint32_t primary;
    int32_t backup;
    uint32_t size;
    uint32_t tourIndex;
    std::vector<uint32_t> feasibleCandidates; // Eq. (2) candidates retained for failover re-election

    uint64_t buffer = 0;       // readings held by the current primary CH
    uint64_t backupBuffer = 0; // last replicated buffer at the backup CH

    // Reliability accounting
    uint64_t lostDuringFailover = 0;
    uint32_t primaryFailures = 0;
    uint32_t backupPromotions = 0;
    double lastFailoverTime = -1.0;
    uint32_t failuresNoBackup = 0;
    uint32_t failuresBackupDead = 0;

    double scheduledWindowEnergyJ = 0.0;

    // Primary failure detection
    uint32_t missedHeartbeatCount = 0;
    bool primaryFailureDetected = false;
    double primaryFailureDetectedTime = -1.0;
    uint64_t bufferLostAtFailure = 0;

    // Data accounting [readings]
    uint64_t generated = 0, overflow = 0, lost154 = 0, lostChDead = 0;
    uint64_t sentWifi = 0, delivered = 0;

    // Contact / wake accounting
    uint32_t visits = 0, contacts = 0, failedContacts = 0;
    uint32_t discoveryContacts = 0;
    uint32_t windowsScheduled = 0, windowsOpened = 0;
    uint32_t windowsMet = 0, windowsMissed = 0;
    double windowListenTime = 0;
    double wifiAwakeTime = 0;
};

struct VisitRecord
{
    uint32_t cluster;
    double departTime, arriveTime, contactTime, endTime; // contactTime < 0: no contact
    double legDistance;
    double promisedEta; // < 0 if no promise was made for this arrival
    double promiseIssuedTime; // Time when the promise was created
    uint64_t readings;
};

class World
{
  public:
    SimConfig cfg;
    std::vector<Sensor> sensors;
    std::vector<Cluster> clusters;
    std::vector<VisitRecord> visits;
    std::vector<uint32_t> tourOrder; // cluster ids in survey-tour order
    double uavRangeM = 80.0;
    double electionAlpha = 0.5;

    // UAV totals
    double uavDistance = 0;
    double uavFlightTime = 0; // includes additional delay time [s]
    double uavDelayTime = 0;  // additional delay component of flight time [s]
    double uavHoverTime = 0;

    void LoadTopology(const std::string& dir);

    double Airtime154() const;
    double SensorEnergyUsed(const Sensor& s, double now) const;
    double Residual(const Sensor& s, double now) const;

    // Called at each Poisson reading arrival of sensor s. hopLost: Bernoulli draw for the
    // abstracted 802.15.4 hop (ignored for readings generated by the CH itself).
    void OnReading(Sensor& s, bool hopLost);
    void ReplicateBuffers();
    bool PromoteBackup(uint32_t clusterId, double now);
    int32_t ElectBackup(uint32_t clusterId, double now);

    void WriteOutputs(double wallSeconds) const;
};

} // namespace wsnuav

#endif
